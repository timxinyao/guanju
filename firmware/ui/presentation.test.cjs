'use strict';
const assert = require('node:assert/strict');
const { IDS, derive, createTvPresentation } = require('./app.js');
const base = { [IDS.intent]: true, [IDS.monitoring]: true, [IDS.radar]: true, [IDS.zone]: 'Clear', [IDS.tv]: 'Active / picture visible', [IDS.scene]: 'Near' };
const presentation = createTvPresentation();
const update = (states, now, alive = true, generation = 1) => presentation.update(states, alive, generation, now);
assert.equal(update({}, 100).kind, 'connecting');
assert.equal(update({ [IDS.tv]: 'Active / picture visible' }, 150).kind, 'connecting');
assert.equal(update(base, 200).kind, 'visible');
const unknown = { ...base, [IDS.tv]: 'Unavailable / state expired' };
assert.deepEqual(update(unknown, 300), { kind: 'visible', title: '画面正常', deadline: 5300 });
assert.equal(update(unknown, 5299).deadline, 5300);
assert.equal(update(unknown, 5300).kind, 'unknown');
assert.equal(update({ ...base, [IDS.tv]: 'Active / pictureOff' }, 5301).kind, 'off');
assert.equal(update({ ...base, [IDS.tv]: 'Standby (will not wake)' }, 5302).kind, 'standby');
assert.equal(update({ ...unknown, [IDS.status]: 'ON; paused: TV communication failed' }, 5303).kind, 'fault');
assert.equal(update({ ...unknown, [IDS.status]: 'ON; paused: TV rejected pictureOff' }, 5304).kind, 'fault');
assert.equal(update(unknown, 5304).kind, 'connecting');
assert.equal(update(unknown, 5305, false).kind, 'offline');
assert.equal(update(unknown, 5306, true, 2).kind, 'connecting');
assert.equal(update(unknown, 10306, true, 2).kind, 'unknown');
assert.equal(update(base, 10307, true, 2).kind, 'visible');
assert.equal(update(unknown, 10308, true, 3).kind, 'connecting');
assert.equal(derive(unknown, true).canRestore, false);
assert.equal(derive({ ...unknown, [IDS.intent]: null }, true).canSwitch, false);
assert.equal(update(unknown, 10309, false, 3).kind, 'offline');
assert.equal(update(base, 10310, true, 3).kind, 'visible');
for (const status of ['ON; command uncertain / failed; recovery pending', 'ON; hide not confirmed; recovery pending', 'ON; RPC stalled; waiting without parallel request']) {
  assert.equal(update({ ...base, [IDS.status]: status }, 10311).kind, 'fault');
}
const unusual = createTvPresentation();
assert.equal(unusual.update({ ...base, [IDS.tv]: 'constructor' }, true, 1, 0).kind, 'connecting');
assert.equal(unusual.update({ ...base, [IDS.tv]: 'constructor' }, true, 1, 5000).kind, 'unknown');
assert.equal(derive(base, false).canSwitch, false);
const initial = createTvPresentation();
assert.equal(initial.update({}, false, 1, 0, true).kind, 'connecting');
assert.equal(initial.update({}, false, 2, 5, false).kind, 'offline');
assert.equal(initial.update(base, true, 3, 10, false).kind, 'visible');
assert.equal(initial.update(base, false, 4, 20, false).kind, 'offline');
assert.equal(initial.update(unknown, true, 5, 21, false).kind, 'connecting');
const invalid = { toString: null };
assert.equal(createTvPresentation().update({ ...base, [IDS.status]: invalid }, true, 1, 0).kind, 'visible');
assert.equal(createTvPresentation().update({ ...base, [IDS.tv]: invalid }, true, 1, 0).kind, 'connecting');
assert.equal(require('./app.js').detailValue(IDS.tv, invalid, true), '状态未知');
assert.equal(require('./app.js').detailValue(IDS.status, invalid, true), '状态未知');
console.log('电视展示计时、会话与故障检查通过');
