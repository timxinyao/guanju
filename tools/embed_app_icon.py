#!/usr/bin/env python3
"""Embed the 180×180 Apple touch icon into a deterministic C++ header."""
import argparse
import pathlib
import struct
import zlib


def validate_png(data: bytes) -> None:
    if not data.startswith(b"\x89PNG\r\n\x1a\n"):
        raise ValueError("input is not a PNG")
    pos = 8
    first = True
    seen_idat = False
    ended = False
    while pos + 12 <= len(data):
        size = struct.unpack_from(">I", data, pos)[0]
        end = pos + 12 + size
        if end > len(data):
            raise ValueError("truncated PNG chunk")
        kind = data[pos + 4:pos + 8]
        payload = data[pos + 8:pos + 8 + size]
        expected_crc = struct.unpack_from(">I", data, pos + 8 + size)[0]
        if zlib.crc32(kind + payload) & 0xFFFFFFFF != expected_crc:
            raise ValueError("invalid PNG chunk checksum")
        if first:
            if kind != b"IHDR" or size != 13 or struct.unpack_from(">II", payload) != (180, 180):
                raise ValueError("PNG must be 180×180 pixels")
            first = False
        if kind == b"IDAT":
            seen_idat = True
        if kind == b"IEND":
            ended = size == 0 and end == len(data)
            break
        pos = end
    if not ended or not seen_idat:
        raise ValueError("incomplete PNG")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("input", type=pathlib.Path)
    parser.add_argument("output", type=pathlib.Path)
    args = parser.parse_args()
    try:
        data = args.input.read_bytes()
        validate_png(data)
    except (OSError, ValueError) as exc:
        parser.error(str(exc))
    lines = ["  " + ", ".join(f"0x{value:02x}" for value in data[i:i + 12]) + ","
             for i in range(0, len(data), 12)]
    args.output.write_text(
        "// Generated by tools/embed_app_icon.py; do not edit.\n"
        "#pragma once\n#include <cstdint>\n\nnamespace tv_trial {\n"
        "static const uint8_t app_icon_png[] = {\n" + "\n".join(lines) +
        "\n};\n}  // namespace tv_trial\n", encoding="utf-8")


if __name__ == "__main__":
    main()
